const ProjectionSHA256 = "e813e272dc6be1f7428d537a328dd392ba2acdce7afc13c8cc04993b09fd42a0"

func digest(b []byte) string    { s := sha256.Sum256(b); return hex.EncodeToString(s[:]) }
func Normalize(s string) string { return strings.Join(strings.Fields(strings.ToLower(s)), " ") }
func ReadRows(filename string) ([]Row, error) {
	b, err := readBounded(filename, 64<<20)
	if err != nil {
		return nil, err
	}
	if digest(b) != ProjectionSHA256 {
		return nil, fmt.Errorf("projection hash mismatch")
	}
	s := bufio.NewScanner(bytes.NewReader(b))
	s.Buffer(make([]byte, 65536), 2<<20)
	var rows []Row
	for s.Scan() {
		var r Row
		d := json.NewDecoder(bytes.NewReader(s.Bytes()))
		d.DisallowUnknownFields()
		if err := d.Decode(&r); err != nil {
			return nil, err
		}
		if err := d.Decode(new(any)); err != io.EOF {
			return nil, fmt.Errorf("trailing JSON")
		}
		rows = append(rows, r)
	}
	if err := s.Err(); err != nil {
		return nil, err
	}
	if len(rows) != 14291 {
		return nil, fmt.Errorf("unexpected rows")
	}
	return rows, nil
}
func readBounded(p string, limit int64) ([]byte, error) {
	f, e := os.Open(p)
	if e != nil {
		return nil, e
	}
	defer f.Close()
	b, e := io.ReadAll(io.LimitReader(f, limit+1))
	if e != nil {
		return nil, e
	}
	if int64(len(b)) > limit {
		return nil, fmt.Errorf("file exceeds budget")
	}
	return b, nil
}
func readEntry(f *zip.File) ([]byte, error) {
	if f.UncompressedSize64 > 8<<20 {
		return nil, fmt.Errorf("archive member exceeds budget")
	}
	r, e := f.Open()
	if e != nil {
		return nil, e
	}
	defer r.Close()
	b, e := io.ReadAll(io.LimitReader(r, (8<<20)+1))
	if len(b) > 8<<20 {
		return nil, fmt.Errorf("archive member exceeds budget")
	}
	return b, e
}

type SourceAudit struct {
	Source                                                                                                                        Source
	Rows, Files, MissingFiles, MismatchedCode, GeneratedRows, NestedNoticeRows, OtherLicenseHeaderRows, QueryInsideCode, Retained int
	NestedNotices                                                                                                                 []string
}

var generated = regexp.MustCompile(`(?i)(code generated|generated by|do not edit)`)
var noticeName = regexp.MustCompile(`(?i)^(license|copying|notice)(\.|$)`)
var otherHeader = regexp.MustCompile(`(?i)(license|copyright)`)

// Exclusion reasons are checked in order. Counts are mutually exclusive.
func Exclusion(r Row, file string, notices []string) string {
	if !strings.Contains(file, r.Code) {
		return "code"
	}
	header := strings.SplitN(file, "package ", 2)[0]
	if generated.MatchString(header) {
		return "generated"
	}
	for _, n := range notices {
		if dir := path.Dir(n); dir != "." && strings.HasPrefix(r.Path, dir+"/") {
			return "notice"
		}
	}
	if !strings.Contains(header, "Apache License") && otherHeader.MatchString(header) {
		return "header"
	}
	q := Normalize(r.Query)
	if q == "" || strings.Contains(Normalize(r.Code), q) {
		return "query"
	}
	return ""
}

func Select(rows []Row, archives string) ([]Row, []SourceAudit, error) {
	var kept []Row
	var audits []SourceAudit
	for _, src := range Sources {
		b, e := readBounded(filepath.Join(archives, src.Archive), 50<<20)
		if e != nil {
			return nil, nil, e
		}
		if digest(b) != src.ArchiveSHA256 {
			return nil, nil, fmt.Errorf("archive hash mismatch: %s", src.Repository)
		}
		z, e := zip.NewReader(bytes.NewReader(b), int64(len(b)))
		if e != nil {
			return nil, nil, e
		}
		entries := map[string]*zip.File{}
		var notices []string
		prefix := ""
		for _, f := range z.File {
			parts := strings.SplitN(f.Name, "/", 2)
			if len(parts) != 2 {
				return nil, nil, fmt.Errorf("invalid archive root")
			}
			if prefix == "" {
				prefix = parts[0]
			}
			if parts[0] != prefix {
				return nil, nil, fmt.Errorf("multiple archive roots")
			}
			if f.FileInfo().IsDir() {
				continue
			}
			p := parts[1]
			if entries[p] != nil {
				return nil, nil, fmt.Errorf("duplicate archive path")
			}
			entries[p] = f
			if noticeName.MatchString(path.Base(p)) {
				notices = append(notices, p)
			}
		}
		f := entries[src.LicensePath]
		if f == nil {
			return nil, nil, fmt.Errorf("missing root license")
		}
		license, e := readEntry(f)
		if e != nil {
			return nil, nil, e
		}
		if digest(license) != src.LicenseSHA256 {
			return nil, nil, fmt.Errorf("root license mismatch")
		}
		a := SourceAudit{Source: src}
		files := map[string]string{}
		nested := map[string]bool{}
		for _, r := range rows {
			if r.Repository != src.Repository {
				continue
			}
			a.Rows++
			if !strings.HasPrefix(r.URL, "https://github.com/"+src.Repository+"/blob/"+src.Revision+"/") {
				return nil, nil, fmt.Errorf("source revision mismatch")
			}
			f := entries[r.Path]
			if f == nil {
				a.MissingFiles++
				continue
			}
			text, ok := files[r.Path]
			if !ok {
				data, e := readEntry(f)
				if e != nil {
					return nil, nil, e
				}
				text = string(data)
				files[r.Path] = text
			}
			switch Exclusion(r, text, notices) {
			case "code":
				a.MismatchedCode++
			case "generated":
				a.GeneratedRows++
			case "notice":
				a.NestedNoticeRows++
				for _, n := range notices {
					if d := path.Dir(n); d != "." && strings.HasPrefix(r.Path, d+"/") {
						nested[n] = true
					}
				}
			case "header":
				a.OtherLicenseHeaderRows++
			case "query":
				a.QueryInsideCode++
			default:
				a.Retained++
				kept = append(kept, r)
			}
		}
		a.Files = len(files)
		for n := range nested {
			a.NestedNotices = append(a.NestedNotices, n)
		}
		sort.Strings(a.NestedNotices)
		audits = append(audits, a)
	}
	// Candidate ordering must not depend on query text or model scores.
	sort.Slice(kept, func(i, j int) bool { return CandidateID(kept[i]) < CandidateID(kept[j]) })
	return kept, audits, nil
}
func CandidateID(r Row) string {
	return digest([]byte(r.Repository + "\x00" + r.Path + "\x00" + r.Code))
}
